"""Keep the documentation pages in step with the rest of the repository.

Run it from the repository root after editing docs/banner.html or one of the
source READMEs (the CI docs workflow runs it too, before every site build):

    python3 docs/sync-imports.py

It does two things:

1. mirrors the READMEs of the assessment folders and of the test images into
   the pages under docs/, so those pages never drift from their source;
2. stamps docs/banner.html at the top of every page of the site, between the
   two markers below — rerun it and the banner is refreshed everywhere.

Nothing here runs at build time: the pages it writes are ordinary Markdown,
readable on GitHub and in any editor.
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
DOCS = ROOT / 'docs'

BEGIN, END = '<!-- banner:begin -->', '<!-- banner:end -->'

# docs page  <-  source README  (+ extra material appended to the page only)
PAGES = {
    'docs/test-images.md': ('orientationj-test-images/README.md', ''),
    'docs/assessment/benchmarking.md': ('assessment/benchmarking/README.md', ''),
    'docs/assessment/gradients.md': ('assessment/gradients/README.md', ''),
    'docs/assessment/operator.md': ('assessment/gst_operator/README.md', ''),
    'docs/assessment/python-port.md': ('assessment/orientationj_python_port/README.md', ''),
}


def mirror_readmes():
    for page, (source, extra) in PAGES.items():
        content = (ROOT / source).read_text(encoding='utf-8').strip()
        header = (f'<!-- AUTO-GENERATED from {source} by docs/sync-imports.py.\n'
                  f'     Do not edit this file: edit the source README, then run\n'
                  f'     `python3 docs/sync-imports.py` from the repository root. -->\n\n')
        (ROOT / page).write_text(header + content + '\n' + extra, encoding='utf-8')
        print(f'{page}  <-  {source}')


def stamp_banner():
    """Write the banner at the top of every page, once, between the markers."""
    banner = (DOCS / 'banner.html').read_text(encoding='utf-8')
    banner = banner[banner.index('<div class="oj-banner">'):].rstrip()

    for page in sorted(DOCS.rglob('*.md')):
        text = page.read_text(encoding='utf-8')
        # How far the page sits below the site root. MkDocs serves foo.md at
        # foo/index.html, so every page but an index.md is one level deeper
        # than its folder — and it does not rewrite paths inside raw HTML.
        parts = page.relative_to(DOCS).parts
        depth = len(parts) - 1 + (0 if page.name == 'index.md' else 1)
        block = banner.replace('src="assets/', f'src="{"../" * depth}assets/')
        stamped = f'{BEGIN}\n{block}\n{END}\n'

        if BEGIN in text:
            text = re.sub(re.escape(BEGIN) + r'.*?' + re.escape(END) + r'\n',
                          stamped, text, count=1, flags=re.S)
        else:
            text = stamped + '\n' + text.lstrip('\n')
        page.write_text(text, encoding='utf-8')
    print(f'banner stamped on {len(list(DOCS.rglob("*.md")))} pages')


if __name__ == '__main__':
    mirror_readmes()
    stamp_banner()
